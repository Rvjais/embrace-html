/**
 * Writes the article body of each locations/<service>-in-<locality>.php from
 * the authored content in location-pages-content.js.
 *
 *     node generate-location-body.js --dry     # report only, write nothing
 *     node generate-location-body.js           # apply
 *     node generate-location-body.js --service child-psychologist
 *
 * Phase 2 of LOCATION-PAGES-BRIEF.md, Option A: all 110 pages rewritten in
 * place. Only services present in SERVICES are touched, so batches can be
 * shipped one at a time without half-written pages reaching the site.
 *
 * The body replaces everything inside <div class="flex-grow max-w-4xl
 * article-content">, and is fenced by LOCATION-BODY markers so re-runs are
 * idempotent. The FAQ markup deliberately matches the shape
 * generate-schema.js reads (Pattern A: div.faq-item, first span is the
 * question, first p is the answer) and the shape interactive.js binds to
 * (.faq-btn), so run generate-schema.js after this to refresh FAQPage nodes.
 *
 * Nothing here invents content. If a service is missing from SERVICES, or a
 * locality from LOCALITIES, the page is skipped and reported rather than
 * filled with a templated stand-in.
 */
const fs = require('fs');
const path = require('path');

const { CENTRES, CLINICIANS, PARTNERS, LOCALITIES, SERVICES } = require('./location-pages-content.js');

const DIR = path.join(__dirname, 'locations');
const DRY = process.argv.includes('--dry');

const onlyIdx = process.argv.indexOf('--service');
const ONLY = onlyIdx > -1 ? process.argv[onlyIdx + 1] : null;

const START = '<!-- LOCATION-BODY:START (generated by generate-location-body.js from location-pages-content.js, do not edit by hand) -->';
const END = '<!-- LOCATION-BODY:END -->';

const OPEN_TAG = '<div class="flex-grow max-w-4xl article-content">';

/**
 * Delhi and South Delhi are served by both Delhi centres, so the clinician
 * list on those pages is drawn from both. Everywhere else has one centre.
 */
const CENTRE_SETS = {
  'delhi': ['vasant-kunj', 'malviya-nagar'],
  'south-delhi': ['malviya-nagar', 'vasant-kunj'],
};

/* ------------------------------------------------------------------- utils */

/** Escape bare ampersands without double-escaping existing entities. */
const enc = s => String(s).replace(/&(?!amp;|lt;|gt;|quot;|#\d+;|[a-z]+;)/g, '&amp;');

const p = t => `<p>${enc(t)}</p>`;
const h2 = t => `<h2>${enc(t)}</h2>`;
const ul = items => `<ul>\n${items.map(i => `<li>${enc(i)}</li>`).join('\n')}\n</ul>`;

/** Count words in the rendered body, for the report. */
const wordCount = html =>
  html.replace(/<[^>]+>/g, ' ').replace(/&[a-z]+;/g, ' ').split(/\s+/).filter(Boolean).length;

/**
 * Walk div depth from an opening tag to its matching close, so the body can be
 * swapped without relying on the exact markup that follows it.
 */
function findBlockEnd(html, openIdx) {
  const re = /<div\b[^>]*>|<\/div>/gi;
  re.lastIndex = openIdx;
  let depth = 0;
  let m;
  while ((m = re.exec(html))) {
    if (m[0].toLowerCase().startsWith('</')) {
      depth--;
      if (depth === 0) return m.index;
    } else {
      depth++;
    }
  }
  return -1;
}

/* ----------------------------------------------------------- body sections */

function factsCard(centre) {
  const rows = [
    ['Centre', centre.name],
    ['Address', centre.address],
  ];
  if (centre.nearestMetro) rows.push(['Nearest metro', centre.nearestMetro]);
  rows.push(['Phone', centre.phone]);

  const items = rows
    .map(
      ([label, value]) =>
        `<li class="flex items-start gap-3">\n` +
        `<img decoding="async" width="100" height="100" alt="Bullet" class="w-4 h-4 flex-shrink-0 mt-1" src="/assets/Diamond-dGu0kMrR.svg"/>\n` +
        `<span class="text-sm md:text-base text-gray-700"><strong>${enc(label)}:</strong> ${enc(value)}</span>\n` +
        `</li>`
    )
    .join('\n');

  return (
    `<div class="key-points-card my-8">\n` +
    `<ul class="space-y-4 key-points-list">\n${items}\n</ul>\n` +
    `</div>`
  );
}

/**
 * A clinician's role and biography can both vary by service. Dr Malik is
 * described as Head of the Child Development Centre on child pages, which is
 * accurate and useful there and simply misleading on an adult counselling page.
 * Where no service-specific version exists, the default is used unchanged.
 */
function bioRole(c, serviceSlug) {
  return (c.roleByService && c.roleByService[serviceSlug]) || c.role;
}

function bioText(c, serviceSlug) {
  if (c.short && typeof c.short === 'object') {
    return c.short[serviceSlug] || c.short.default || c.line;
  }
  return c.short || c.line;
}

/** Named clinicians at the centres that serve this locality, for this service. */
function whoYouWouldSee(service, serviceSlug, localitySlug, locality) {
  const centreSlugs = CENTRE_SETS[localitySlug] || [locality.centre];

  const named = Object.values(CLINICIANS).filter(
    c =>
      Array.isArray(c.services) &&
      c.services.includes(serviceSlug) &&
      c.centres.some(x => centreSlugs.includes(x))
  );

  const centreNames = centreSlugs.map(s => CENTRES[s].shortName || CENTRES[s].name);
  const heading =
    centreSlugs.length > 1
      ? 'Who you would see'
      : `Who you would see at ${centreNames[0]}`;

  const out = [h2(heading)];

  // Dr Supriya Malik is the page-level clinical authority on every location
  // page: she designed the pathways the centres run. The clinicians below her
  // are the people a family from this locality actually sits with.
  const malik = CLINICIANS['supriya-malik'];
  out.push(`<h3>${enc(malik.name)}, ${enc(bioRole(malik, serviceSlug))}</h3>`);
  out.push(p(bioText(malik, serviceSlug)));

  // Some services genuinely are not staffed at every centre. Saying so beats a
  // vague reassurance: on a page about a service the local centre does not
  // offer, it is the single most useful sentence available.
  const coverageNote = service.coverage && service.coverage[centreSlugs[0]];
  if (!named.length) {
    out.push(
      p(
        coverageNote ||
        `The clinician you see is matched on the intake call to what your child needs, which centre suits you and which language you would rather work in. We tell you who it will be before you book, not on the day.`
      )
    );
    return out.join('\n');
  }

  out.push(
    p(
      centreSlugs.length > 1
        ? `Across our Delhi centres, the clinicians who take this work are:`
        : `At ${centreNames[0]}, the clinicians who take this work are:`
    )
  );
  // centreNames already reads "our Malviya Nagar centre", so the sentence above
  // must not prefix it again.

  for (const c of named) {
    out.push(`<h3>${enc(c.name)}, ${enc(bioRole(c, serviceSlug))}</h3>`);
    out.push(p(bioText(c, serviceSlug)));
  }

  out.push(
    p(
      `Which of them you see is decided on the intake call rather than by whoever has the next free slot, and you are told who it will be before you book. Fuller biographies are on our <a href="/about">about page</a>.`
    )
  );

  return out.join('\n');
}

/**
 * School and institutional work relevant to this locality.
 *
 * A service may override the list. School partnerships carry no weight on an
 * adult counselling page and corporate ones carry a great deal, so the set is
 * chosen by service where the locality default would be simply irrelevant.
 */
function partnerSection(locality, localitySlug, service) {
  // partnersOverride may be a flat array, or an object keyed by locality with a
  // `default`. The object form matters: a single shared list across all ten
  // localities removes one of the few things that differentiates them.
  const ov = service.partnersOverride;
  const keys = Array.isArray(ov)
    ? ov
    : ov
      ? (ov[localitySlug] || ov.default || [])
      : (locality.partners || []);
  const list = keys.map(k => PARTNERS[k]).filter(Boolean);
  if (!list.length) return '';

  return [
    h2('Schools and services we already work with'),
    p(
      service.partnerIntro
        ? service.partnerIntro(locality)
        : `Some of what we do around ${locality.name} happens inside institutions rather than at a centre, which is often how a family first hears of us.`
    ),
    ...list.map(x => p(x.sentence)),
  ].join('\n');
}

function faqSection(service, localitySlug) {
  const faqs = (service.faqs && service.faqs[localitySlug]) || service.faqs.default;

  const items = faqs
    .map(
      f =>
        `<div class="faq-item">\n` +
        `<button class="w-full text-left flex justify-between items-center focus:outline-none faq-btn">\n` +
        `<span class="font-semibold text-base md:text-lg text-[#234394] group-hover:text-purple-600 transition-colors">${enc(f.q)}</span>\n` +
        `<svg class="faq-icon" fill="none" stroke="#234394" stroke-linecap="round" stroke-width="2" viewbox="0 0 24 24"><path d="M12 5v14M5 12h14"></path></svg>\n` +
        `</button>\n` +
        `<div class="transition-all duration-300 max-h-0 opacity-0 overflow-hidden">\n` +
        `<p class="text-sm md:text-base text-gray-600 mt-2 pb-2 leading-relaxed">${enc(f.a)}</p>\n` +
        `</div>\n` +
        `</div>`
    )
    .join('\n');

  return `<h2>Frequently asked questions</h2>\n<div class="space-y-2 mb-8">\n${items}\n</div>`;
}

function ctaSection(service, locality) {
  return (
    `<div class="cta-card my-12">\n` +
    `<h3 class="text-xl md:text-2xl font-bold text-gray-800 mb-2">Book, or check first</h3>\n` +
    `<p class="text-sm md:text-base text-gray-600 mb-6 max-w-xl mx-auto">Start with the free 15-minute intake call. It is with a clinician, fees are quoted on it, and if we are not the right service for your child we will tell you on that call rather than after you have paid for an appointment.</p>\n` +
    `<a href="/appointment" class="inline-block bg-[#234394] text-white px-8 py-3 rounded-full hover:bg-blue-800 font-semibold cursor-pointer shadow">Book a free intake call</a>\n` +
    `</div>`
  );
}

/* ------------------------------------------------------------- composition */

function buildBody(serviceSlug, localitySlug) {
  const service = SERVICES[serviceSlug];
  const locality = LOCALITIES[localitySlug];
  const centre = CENTRES[locality.centre];

  // Used by the service lede. Kept here rather than in the content module so
  // the wording stays consistent across every service that gets written.
  // The full address is carried by the facts card immediately below the lede,
  // so the lede names the centre without repeating the street line.
  // Three cases, not two. The old two-way test compared locality.centre with
  // the locality slug, which is only ever true for Vasant Kunj, so Gurgaon,
  // Delhi and South Delhi were all told we have no centre there. All three are
  // false: the Gurugram centre is in Gurgaon, and both Delhi centres are in
  // south Delhi. That was wrong on 51 pages.
  const CENTRE_IS_HERE = { 'vasant-kunj': 'Vasant Kunj', 'gurgaon': 'Gurgaon' };
  const BOTH_CENTRES = {
    'delhi': 'both our Delhi centres, Vasant Kunj and Malviya Nagar',
    'south-delhi': 'either of our two south Delhi centres, Malviya Nagar or Vasant Kunj',
  };
  const leadCentreSentence = BOTH_CENTRES[localitySlug]
    ? `The short answer is ${BOTH_CENTRES[localitySlug]}, and which one is a question of your journey rather than of the service.`
    : CENTRE_IS_HERE[localitySlug]
      ? `The centre is in ${CENTRE_IS_HERE[localitySlug]} itself.`
      : `The short answer is ${centre.shortName || centre.name}, because we do not have a centre in ${locality.name}.`;

  const parts = [];

  parts.push(p(service.lede({ ...locality, leadCentreSentence })));
  parts.push(factsCard(centre));

  // The differentiator: which centre, and how a family from here reaches it.
  parts.push(h2(locality.heading));
  locality.gettingThere.forEach(t => parts.push(p(t)));

  // What the travel commitment actually is for THIS service. A weekly therapy
  // course and a two-visit assessment are different propositions from the same
  // address, so this is authored per service and sits inside the locality
  // section. It is also one of the few honest ways to differentiate two
  // services that share a centre, a roster and a catchment.
  const cadence =
    (service.cadenceByLocality && service.cadenceByLocality[localitySlug]) || service.cadence;
  if (cadence) parts.push(p(cadence));

  // Parking and door-to-door timings were not supplied by the client and are
  // not worth guessing at, so this points people at the intake call instead of
  // asserting something a parent would plan a journey around. Metro lines,
  // stations, stop counts and road names are used elsewhere because those are
  // checkable and stable; minute-counts and parking are neither.
  // Localities with no centre of their own are online-first, so a paragraph
  // about parking as though it were a weekly drive reads wrong on those pages.
  parts.push(
    p(
      locality.onlineFirst
        ? `On the occasions you do travel in for an in-person appointment, ask about parking and the nearest drop-off point on the intake call. Current directions from someone who works there beat anything we could fix on a web page.`
        : `For parking, the nearest drop-off point and the quickest route at your particular time of day, ask on the intake call. Traffic and parking around every one of these centres change enough through the day that current directions from someone who works there beat anything we could fix on a web page.`
    )
  );

  // When the service is warranted, and when it is not. Kept short on purpose;
  // the full treatment lives on the hub rather than ten times over here.
  parts.push(h2(service.whenRight.h2));
  service.whenRight.paras.forEach(t => parts.push(p(t)));
  if (service.whenRight.list.length) parts.push(ul(service.whenRight.list));
  (service.whenRight.after || []).forEach(t => parts.push(p(t)));
  if (service.whenRight.hubLink) {
    parts.push(
      `<p>${enc(service.whenRight.hubLink).replace(
        `${service.hubName.toLowerCase()}`,
        `<a href="${service.hub}">${service.hubName.toLowerCase()}</a>`
      )}</p>`
    );
  }

  parts.push(h2(service.firstAppointment.h2));
  service.firstAppointment.paras.forEach(t => parts.push(p(t)));
  if (service.firstAppointment.list.length) parts.push(ul(service.firstAppointment.list));
  (service.firstAppointment.after || []).forEach(t => parts.push(p(t)));

  // Written per locality where the picture genuinely differs.
  parts.push(h2(service.seenMost.h2));
  (service.seenMost[localitySlug] || service.seenMost.default).forEach(t => parts.push(p(t)));

  parts.push(whoYouWouldSee(service, serviceSlug, localitySlug, locality));

  const partners = partnerSection(locality, localitySlug, service);
  if (partners) parts.push(partners);

  parts.push(h2(service.timelines.h2));
  service.timelines.paras.forEach(t => parts.push(p(t)));

  parts.push(faqSection(service, localitySlug));
  parts.push(ctaSection(service, locality));

  return parts.join('\n');
}

/* -------------------------------------------------------------------- main */

const stats = { written: 0, skippedService: new Set(), skippedOther: [], words: [] };

for (const file of fs.readdirSync(DIR).sort()) {
  if (!file.endsWith('.php') || file === 'index.php') continue;

  const m = file.replace(/\.php$/, '').match(/^(.+)-in-(.+)$/);
  if (!m) { stats.skippedOther.push(`${file} (filename does not match <service>-in-<locality>)`); continue; }

  const [, serviceSlug, localitySlug] = m;
  if (ONLY && serviceSlug !== ONLY) continue;

  if (!SERVICES[serviceSlug]) { stats.skippedService.add(serviceSlug); continue; }
  if (!LOCALITIES[localitySlug]) { stats.skippedOther.push(`${file} (no locality profile for "${localitySlug}")`); continue; }

  const full = path.join(DIR, file);
  let html = fs.readFileSync(full, 'utf8');

  const body = `${START}\n${buildBody(serviceSlug, localitySlug)}\n${END}`;

  if (html.includes(START) && html.includes(END)) {
    // Re-run: swap what is between the markers.
    const a = html.indexOf(START);
    const b = html.indexOf(END) + END.length;
    html = html.slice(0, a) + body + html.slice(b);
  } else {
    // First run: replace everything inside the article-content div.
    const openIdx = html.indexOf(OPEN_TAG);
    if (openIdx === -1) { stats.skippedOther.push(`${file} (no article-content block found)`); continue; }
    const closeIdx = findBlockEnd(html, openIdx);
    if (closeIdx === -1) { stats.skippedOther.push(`${file} (unbalanced article-content block)`); continue; }
    html = html.slice(0, openIdx + OPEN_TAG.length) + '\n' + body + '\n' + html.slice(closeIdx);
  }

  stats.words.push([file, wordCount(body)]);
  stats.written++;
  if (!DRY) fs.writeFileSync(full, html);
}

console.log(`${DRY ? '[dry run] ' : ''}Location bodies written: ${stats.written}`);
for (const [file, w] of stats.words) console.log(`  ${String(w).padStart(5)} words  ${file}`);
if (stats.skippedService.size) {
  console.log(`\nServices not yet authored in location-pages-content.js (pages left untouched):`);
  console.log(`  ${[...stats.skippedService].sort().join(', ')}`);
}
if (stats.skippedOther.length) {
  console.log(`\nSkipped:`);
  for (const s of stats.skippedOther) console.log(`  ${s}`);
}
if (!DRY && stats.written) {
  console.log(`\nNext: node generate-location-meta.js && node generate-schema.js`);
}
