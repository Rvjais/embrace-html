<h2>What the first appointment involves</h2>
<p>An assessment of the structures and their movement, and wherever possible watching your child actually eat or drink, because that shows things a clinic task will not. We take a feeding history and check what has already been tried. You leave with a plan aimed at mealtimes, not at exercises for their own sake.</p>
<h2>What we see most of</h2>
<p>At Malviya Nagar the commonest referrals are restricted food ranges in toddlers, feeding difficulty in children with cerebral palsy or low tone, and support after cleft lip and palate repair. Because it runs inside Rainbow, a child needing paediatric input as well is not sent to a second address.</p>
