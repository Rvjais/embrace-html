<p>eMbrace at Rainbow, Malviya Nagar, at FC-29, Plot No. 5, Geetanjali, beside Malviya Nagar Metro Station Gate No. 1, serves the Yellow Line corridor through Saket, Hauz Khas and Green Park, and the drive-in catchment of Greater Kailash and Defence Colony. It runs inside Rainbow Children's Hospital, so multidisciplinary therapy sits in the same building as assessment.</p>
<p>If you are in north or west Delhi, either centre is a real journey, and we would usually suggest starting online and coming in only for the parts that have to happen in a room.</p>
<p>Sessions run weekly or twice weekly, and unlike our therapy services a good deal of the value sits outside them, in what a school agrees to do differently. That means the liaison work matters as much as the teaching hours, and it is worth telling us on the intake call how willing your child’s school is to adapt, because it changes what we aim at.</p>
<p>For parking, the nearest drop-off point and the quickest route at your particular time of day, ask on the intake call. Traffic and parking around every one of these centres change enough through the day that current directions from someone who works there beat anything we could fix on a web page.</p>
<h2>When special education is the right answer</h2>
<p>It is the right answer when a child has the ability to learn the material and cannot access it the way it is being delivered. It is the wrong answer when the underlying issue has not been identified yet, which is why a good deal of this work follows an assessment rather than preceding one.</p>
<ul>
<li>Years of extra tuition that has not closed the gap</li>
<li>An assessment identifying dyslexia, dysgraphia, dyscalculia or an intellectual disability, with nobody teaching to it</li>
<li>A child falling further behind each year despite understanding the ideas when they are explained aloud</li>
<li>A school willing to adapt but unsure what to actually change</li>
</ul>
<p>How we work with schools directly is set out on our <a href="/schools-hub/schools">schools partnership hub</a>.</p>
<h2>How the work is planned</h2>
<p>It starts with a written baseline of what a child can currently do, taken from testing and from their actual schoolwork rather than from marks. From that we write an individualised education plan: a small number of targets, the methods that will be used, and a date on which it is reviewed.</p>
<p>The teaching itself is structured and multisensory, particularly for literacy and number, which means material is presented through more than one channel and built in a deliberate sequence rather than assumed. Progress is measured against the plan, not against the class.</p>
<h2>What the work looks like here</h2>
<p>Across our Delhi centres the work is structured literacy and numeracy teaching, individualised education plans and school liaison, usually following an assessment that identified a specific difficulty.</p>
<p>The city-wide pattern is years of tuition preceding the referral. It is worth saying plainly: if three years of extra teaching has not closed a gap, the problem is not the amount of teaching.</p>
