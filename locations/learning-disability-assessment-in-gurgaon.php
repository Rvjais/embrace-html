<h2>When an assessment is worth doing</h2>
<p>The pattern that warrants testing is unexpected underachievement: a child who understands the material in conversation, works as hard as their classmates or harder, and whose written output does not reflect either. What we are looking for is a specific gap, not general difficulty, and a large part of the work is ruling out the ordinary explanations first.</p>
<ul>
<li>Reading that is slow, effortful or inaccurate well past the age when it should have become automatic</li>
<li>Spelling and written work far below the quality of the same child’s spoken answers</li>
<li>Mathematics difficulty confined to number, where reasoning elsewhere is fine</li>
<li>Vision, hearing, attendance, language of instruction and teaching quality all considered and excluded first</li>
</ul>
<p>Dyslexia, dysgraphia, dyscalculia, exam accommodations and academic intervention each have their own page on our <a href="/learning-disabilities/specific-learning-disability">learning disabilities hub</a>.</p>
<h2>What the testing actually measures</h2>
<p>Two things, held against each other. First, general cognitive ability, so we know what this person is capable of. Second, the specific academic skills, reading accuracy and speed, comprehension, spelling, written expression and number, measured individually rather than inferred from school marks. In India that commonly draws on the NIMHANS battery for specific learning disability alongside the Wechsler scales.</p>
<p>School evidence goes in too: exercise books, report cards and the observations of whoever teaches the subject. A report written without them is weaker, and boards notice.</p>
<h2>What brings families here</h2>
<p>From Gurugram most referrals come through schools that already have learning support teams, so the classroom evidence tends to be well documented before we start. That makes the assessment faster and the report stronger.</p>
<p>Adults are a growing second group, usually people who suspected something through school, were never tested, and now need it named for a workplace or a professional exam.</p>
