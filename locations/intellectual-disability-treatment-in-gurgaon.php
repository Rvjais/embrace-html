<h2>Assessment first, and why it matters</h2>
<p>A proper assessment covers cognitive ability and adaptive functioning together, because the second predicts daily life far better than the first does. Two people with similar scores can live very differently depending on what they have been taught and what has been adapted around them.</p>
<p>On paperwork: what we provide is a clinical assessment. A disability certificate under the Rights of Persons with Disabilities Act is issued by a government medical board through its own process, and we explain that route rather than leaving you to discover it later.</p>
