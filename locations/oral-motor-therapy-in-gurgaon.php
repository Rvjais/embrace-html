<h2>When oral motor therapy helps</h2>
<p>This sits between speech and feeding, because the same muscles do both. It is worth an assessment when eating, drinking or speech sounds are affected by how the mouth is working rather than by what a child understands or intends.</p>
<ul>
<li>Coughing, gagging or distress during meals, which warrants prompt attention at any age</li>
<li>A very narrow range of accepted foods or textures, beyond ordinary fussiness</li>
<li>Drooling well past the usual age, or an open mouth posture</li>
<li>Speech sounds that are unclear because of tongue, lip or jaw movement rather than language</li>
<li>Feeding difficulty after cleft repair, or with cerebral palsy or low tone</li>
</ul>
