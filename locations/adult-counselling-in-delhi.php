<h2>When counselling is worth starting</h2>
<p>There is no threshold you have to cross to deserve therapy, and the commonest reason people give for not starting sooner is that other people have it worse. That is true of almost everyone and it is not a useful test. A more useful one is whether something has been going on long enough that you have stopped expecting it to lift on its own.</p>
<ul>
<li>Low mood, anxiety or irritability that has become the normal setting rather than a bad patch</li>
<li>Burnout: still functioning at work, running on empty, and no longer recovering at weekends</li>
<li>A bereavement, separation, diagnosis or move that has not settled the way you assumed it would</li>
<li>The same pattern repeating across relationships, jobs or friendships</li>
<li>Drinking, working or scrolling noticeably more in order to not think about something</li>
</ul>
<p>Anxiety, depression, burnout, grief, workplace stress, trauma and relationship difficulties each have their own page on our <a href="/adult-mental-health/adult-counselling">adult mental health hub</a>.</p>
<h2>What the first session is like, and who knows about it</h2>
<p>The first session is a conversation, not an assessment. By the end you should have a plain-language account of what seems to be going on and a suggested way of working. You are not obliged to continue and you will not be sold a package.</p>
<p>On discretion, which people ask about far more than method: what you say stays between you and your therapist. Nothing reaches your employer, family or doctor without your written consent, including where an employer is paying. The only limit is serious risk.</p>
