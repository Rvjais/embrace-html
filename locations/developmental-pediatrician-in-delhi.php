<h2>What this work covers</h2>
<p>The developmental question is whether a child is progressing as expected across communication, motor, cognitive, social and self-care skills, and if not, why. Some of the answers are developmental, which is our work. Some are medical, which is not.</p>
<ul>
<li>Milestones delayed in one area or several, where the cause has not been established</li>
<li>Regression, meaning loss of skills previously held, which needs prompt medical as well as developmental review</li>
<li>Developmental concerns alongside prematurity, a genetic condition or a birth complication</li>
<li>A developmental difficulty where a medical explanation has not yet been excluded</li>
</ul>
