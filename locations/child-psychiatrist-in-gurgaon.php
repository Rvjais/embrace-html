<p>Delhi families sometimes choose Gurugram over our Delhi centres simply because the Mehrauli-Gurgaon Road run is easier from where they live than crossing south Delhi. Either centre is fine, and the same pathway runs at both.</p>
<p>Where a psychiatric opinion looks relevant, we coordinate the referral to Sukoon directly rather than leaving you to search for a provider, and with your consent we share the assessment and therapy notes that matter so the psychiatric opinion is informed by the same picture your therapist is working from.</p>
<p>For parking, the nearest drop-off point and the quickest route at your particular time of day, ask on the intake call.</p>
<h2>How we work alongside psychiatric care</h2>
<p>A diagnosis such as ADHD, anxiety, depression or OCD in a child or teen frequently has both a psychological side and a medical one, and families should not have to manage two unconnected files to get a coherent plan. That is the work we do.</p>
<ul>
<li>Psychological assessment and diagnosis for ADHD, autism, anxiety, depression and OCD</li>
<li>Therapy for the child or teen, and support for the family around a diagnosis</li>
<li>A coordinated referral to Sukoon across Delhi NCR where a psychiatric and medication opinion is relevant</li>
<li>School liaison and accommodations support, whether or not medication is part of the plan</li>
</ul>
<p>What each part involves is set out on our <a href="/child-psychiatrist">child psychiatry coordination</a> page.</p>
<h2>What we do, and what we do not</h2>
<p>We carry out psychological assessment and deliver therapy, and build a written picture a psychiatrist can read alongside their own findings. We do not diagnose from a purely medical standpoint, prescribe or manage medication ourselves.</p>
<p>If a psychiatric opinion looks relevant and you have not yet had one, we will say so plainly rather than continuing a therapy programme around an unanswered medical question.</p>
