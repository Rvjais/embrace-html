<p>Blocks of weekly sessions with a home programme between them, and the home programme is what moves things. Muscles respond to what happens most days, not to what happens on a Thursday, so we would rather set five minutes daily that you will actually do than twenty you will not.</p>
<p>For parking, the nearest drop-off point and the quickest route at your particular time of day, ask on the intake call. Traffic and parking around every one of these centres change enough through the day that current directions from someone who works there beat anything we could fix on a web page.</p>
<h2>When physiotherapy is the right call</h2>
<p>Physiotherapy is for movement itself: tone, strength, balance, coordination and how a child gets from one position to another. Where the difficulty is with a task rather than with movement, occupational therapy is the better fit, and we say so on the intake call rather than take the booking.</p>
<ul>
<li>Not sitting, crawling or walking within the expected range, or a marked difference between the two sides of the body</li>
<li>Low or high muscle tone affecting posture, feeding position or endurance</li>
<li>Cerebral palsy, neurological conditions, or physical recovery after illness or surgery</li>
<li>A child who tires far faster than peers in physical activity</li>
</ul>
