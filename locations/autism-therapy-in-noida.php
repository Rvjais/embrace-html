<h2>How Noida families see us</h2>
<p>We should be straight about this one: eMbrace has no centre in Noida. Our three centres are in Vasant Kunj, Malviya Nagar and Gurugram, and from most of Noida that is a genuine cross-city journey with a Blue Line to Yellow Line change at Rajiv Chowk.</p>
<p>So for most Noida families the sensible answer is online. Consultation, parent sessions, feedback appointments and a good deal of therapy run perfectly well over video, and it removes the part of the process that most often causes families to drop out, which is the travel.</p>
<p>Where an in-person appointment is genuinely necessary, and cognitive and psychoeducational assessment is the clearest case, we usually schedule it at Malviya Nagar and try to group the testing so you make the trip once rather than weekly. If your child is at school in south Delhi, that often works out easier than it sounds.</p>
<p>This is the heaviest commitment we offer: potentially two or three appointments a week across different disciplines, sustained over months, so the journey is not a detail. Be blunt on the intake call about what your week can carry. A smaller programme that runs for a year beats an ambitious one abandoned in six.</p>
<p>On the occasions you do travel in for an in-person appointment, ask about parking and the nearest drop-off point on the intake call. Current directions from someone who works there beat anything we could fix on a web page.</p>
<h2>What the therapy is aiming at</h2>
<p>The goal is a child who can communicate what they need, take part in what matters to them, and spend less of the day distressed. It is not making an autistic child indistinguishable from a non-autistic one. That distinction changes which goals go in the plan, so it is worth asking any provider where they stand before you commit.</p>
<ul>
<li>Communication, whether spoken, signed or through a device, so a child can get needs and ideas across</li>
<li>Regulation and sensory strategies, so the day contains fewer overwhelming moments</li>
<li>Participation at home and at school, measured in what a child can join in with</li>
<li>Parent and sibling support, because the programme runs at home far more hours than it runs with us</li>
</ul>
<p>Behaviour therapy, sleep, feeding, emotional regulation and autism with ADHD each have their own page on our <a href="/autism/autism">autism hub</a>.</p>
<h2>What a programme is made of</h2>
<p>A programme draws on behaviour therapy and parent training, speech and language therapy, occupational therapy, special education for school access, and physiotherapy where movement is affected. For the youngest children it is organised around naturalistic early intervention, embedded in play and daily routines rather than delivered at a table.</p>
<p>What we will not do is put every child on the same package. The plan starts from a written baseline, names a few goals in terms you could check yourself, and is reviewed on a set date. If a goal is not moving, the plan changes.</p>
<h2>What programmes tend to look like here</h2>
<p>Noida families run the largest online component of any catchment, and for autism therapy that works better than people expect: parent coaching, which is the part that carries most of the change, is well suited to video, and a therapist watching your actual living room is more useful than one imagining it.</p>
<p>What does not work remotely is hands-on occupational therapy and physiotherapy. Where a programme needs those we say so and we plan the travel around them rather than pretending.</p>
