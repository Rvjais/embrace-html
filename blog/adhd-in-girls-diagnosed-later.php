          <p class="text-lg text-gray-700 leading-relaxed font-light">She is not climbing the furniture. She does not disrupt the class. Her teachers describe her as sweet, a bit dreamy, someone who could do better if she applied herself. So nobody has ever suggested assessing her, and you have half-convinced yourself you are imagining it.</p>

          <p>That description is the single most common reason ADHD in girls goes unnoticed. Not because the condition is rare in girls, but because the version of it that gets recognised is the version that interrupts other people.</p>

          <h2>The gap is real, and it is measurable</h2>

          <p>A 2024 UK population cohort study of 9,991 young people, published in <em>JCPP Advances</em>, split children with ADHD into three groups: those recognised early, those recognised later, and those whose ADHD was never identified at all.</p>

          <p>The proportions tell the story. Among children diagnosed early, 19.3% were girls. Among those whose ADHD went entirely unrecognised, 38.7% were girls. Put as ratios, boys outnumbered girls 4.2 to one in the early-diagnosed group, and only 1.6 to one in the missed group.</p>

          <p>Read that twice, because it is the whole argument. As you move from the children the system caught to the children it never caught, the gender gap very nearly closes. ADHD is not anywhere near as uncommon in girls as diagnosis rates suggest. Girls are simply concentrated in the group nobody assessed.</p>

          <h2>Why hyperactivity became the test</h2>

          <p>ADHD has three recognised presentations: predominantly inattentive, predominantly hyperactive and impulsive, and combined. Only one of them disrupts anybody other than the child.</p>

          <p>A boy who cannot stay in his seat creates a problem for the teacher, and problems for teachers get escalated. A girl who is physically still and mentally elsewhere creates a problem only for herself, and it surfaces as marks that do not match her ability. One triggers a referral. The other triggers a line on a report card. Girls are more likely to have the inattentive presentation, so the commonest form of ADHD in girls is the form least likely to be noticed by the adults placed to notice it.</p>

          <h2>What it looks like in a girl who is coping</h2>

          <p>Inattentive ADHD is a poor name for it. The attention is not absent, it is unregulated, and it lands where it wants rather than where it is needed. In a school-age girl that often looks like this.</p>

          <ul class="signs-list">
            <li><strong>Homework that swallows the evening.</strong> Forty minutes of work taking three hours behind a closed door, with the struggle invisible because the finished book looks fine.</li>
            <li><strong>Losing the thread mid-sentence.</strong> Drifting during conversations and instructions, then filling the gap by guessing rather than asking, because asking twice is embarrassing.</li>
            <li><strong>Exhausting tidiness, or none at all.</strong> Either an elaborate system of lists and colour-coded folders that collapses every few weeks, or a bag nothing survives.</li>
            <li><strong>Effort that does not show up in output.</strong> Understanding the lesson, revising for hours, then losing marks to skipped questions and misread instructions.</li>
            <li><strong>Social fatigue.</strong> Managing friendships takes visible effort, and the recovery afterwards looks like moodiness or withdrawal.</li>
            <li><strong>Emotions at full volume.</strong> Feedback that others shrug off lands hard and takes a long time to settle.</li>
            <li><strong>Perfectionism as a coping strategy.</strong> Rewriting the same page repeatedly and starting assignments the night before, because only pressure makes starting possible.</li>
          </ul>

          <p>Any one of these on its own means very little. What matters is a cluster that has been there since early childhood, that shows up in more than one setting, and that costs her something real. Our overview of <a href="/adhd/adhd-symptoms">ADHD symptoms and characteristics</a> covers how the same condition presents differently at different ages.</p>

          <h2>Being capable makes it more likely to be missed</h2>

          <p>This is the part that upends most parents' reasoning, and it comes from the same UK cohort. Compared with the children who were diagnosed, those whose ADHD went unrecognised had higher cognitive ability, better prosocial skills, and fewer emotional and behavioural difficulties. In plain terms, the brighter and better behaved a child was, the more likely her ADHD was to go unidentified.</p>

          <p>So the reassurance you have been offered, that she is doing fine, she is bright, she is no trouble, is not evidence against ADHD. In this data it is the profile of a child who gets missed. The authors' own recommendation was that clinicians should assess for ADHD regardless of cognitive ability or social functioning when the symptoms are present.</p>

          <h2>Girls arrive by a different door</h2>

          <p>When girls are eventually seen, they tend to arrive for a different reason. A Swedish study reviewed the records of 100 children with ADHD, 50 boys and 50 girls. It is a small sample, but the pattern it describes is one clinicians recognise.</p>

          <p>Girls were significantly older at their first visit to child psychiatry, 12.7 years on average against 11.4 for boys. Boys were referred for developmental concerns. Girls were referred for emotional symptoms. Before anyone named ADHD, the girls had made more visits to the clinic, had more often been prescribed medication for something else, and had more often been admitted for acute psychiatric symptoms.</p>

          <p>The sequence matters. Anxiety and low mood are not usually competing explanations for undiagnosed ADHD. They are frequently what grows on top of it after years of falling short of your own capability without knowing why. Treating the anxiety alone leaves the engine running underneath.</p>

          <h2>What this looks like in an Indian classroom</h2>

          <p>A 2026 review of ADHD in India, published in <em>Frontiers in Psychiatry</em>, describes conditions that make this harder here than the international research alone suggests. It reports that ADHD is markedly under-diagnosed across the country, that awareness among educators is limited, and that specialist services are concentrated in metropolitan centres.</p>

          <p>Two observations matter most for daughters. Teachers frequently label affected children unmotivated or careless rather than pursuing assessment, and the behaviour is widely read as indiscipline or poor upbringing, which pushes families towards tuition and stricter rules instead.</p>

          <p>Layer that on a girl with the inattentive presentation and you have a child almost designed to be overlooked. She is not disruptive, so she is not escalated. She is not failing outright, so she is not a priority. She is simply, year after year, described as not applying herself.</p>

          <h2>What an assessment actually looks at</h2>

          <p>There is no blood test or scan for ADHD. The diagnosis is clinical. Under DSM-5, a child under 17 needs six or more symptoms of inattention, or six or more of hyperactivity and impulsivity, or both. Several must have been present before age 12, they must cause difficulty in two or more settings such as home and school, and they must not be better explained by something else.</p>

          <p>That last clause is why a school report settles nothing on its own. A structured <a href="/adhd/adhd-assessment">ADHD assessment</a> combines a clinical interview, rating scales completed by more than one adult who knows her, a developmental history reaching into early childhood, and screening for the anxiety, mood and learning difficulties that often accompany it.</p>

          <div class="safety-card">
            <p><strong>Worth saying plainly:</strong> this article can help you decide whether to ask the question. It is not a diagnosis and not a substitute for assessment by a qualified clinician. Recognising your daughter in a description is a reason to seek an opinion, not a reason to conclude one. If her mood or anxiety has changed noticeably, raise that with a professional too rather than waiting.</p>
          </div>

          <h2>When to ask</h2>

          <p>You do not need a teacher to raise it first. In the research above, waiting for the school to notice is precisely the mechanism that delays girls by years. If the pattern has been there since she was small, shows up at home and at school, and is genuinely costing her, that is enough to justify a conversation.</p>

          <p>A diagnosis is not a label she has to carry. It is an explanation that makes the right support available, and it arrives far more usefully at ten than at twenty-five. What the full delay looks like is set out in our piece on the <a href="/blog/symptoms-of-adhd-in-adulthood">symptoms of ADHD in adulthood</a>, where the same traits get read as character flaws, and our page on <a href="/adhd/adhd-in-women">ADHD in women and girls</a> covers how the presentation carries forward.</p>

