          <p class="text-lg text-gray-700 leading-relaxed font-light">Look up the early signs of autism in toddlers and you will meet the same sentence everywhere. He does not make eye contact. It is the one sign every parent has heard of, and on its own it tells you very little.</p>

          <p>The questionnaire your paediatrician actually uses asks about twenty things. Eye contact is one of them, and it is not the one carrying the most weight. This is what the M-CHAT asks instead, and what a score does and does not tell you.</p>

          <h2>Eye contact is one question out of twenty</h2>

          <p>Eye contact is easy to notice and easy to misread. Toddlers look away when they are absorbed, shy, tired or simply busy. Many autistic children do make eye contact, and many children who are not autistic go through weeks of avoiding it.</p>

          <p>What separates the two more reliably is not whether your child looks at you. It is whether your child brings you into what they are looking at. Researchers call this joint attention, and it runs through the whole checklist.</p>

          <p>Picture an eighteen month old who spots a dog across the park. She points at it, then turns to check that you saw it too. The pointing is not a request. It is an invitation to share a moment. That small loop, notice something, point, look back, is socially complex, and its absence is a far more specific early sign than a child who will not hold your gaze.</p>

          <h2>What the M-CHAT actually is</h2>

          <p>The Modified Checklist for Autism in Toddlers, Revised with Follow-Up, usually shortened to M-CHAT-R/F, is a twenty question screener that a parent fills in. It takes around five minutes, requires no clinical observation, and is free to use. It is validated for children aged 16 to 30 months.</p>

          <p>The American Academy of Pediatrics recommends autism-specific screening for every child at the 18 and 24 month visits, alongside general developmental screening at 9, 18 and 30 months and developmental surveillance at every visit. The Centers for Disease Control and Prevention endorses the same schedule.</p>

          <p>One point matters more than the rest. The CDC states plainly that screening tools do not provide conclusive evidence of developmental delays and do not result in diagnoses. The M-CHAT tells you whether a closer look is warranted. It cannot tell you whether your child is autistic. Our page on <a href="/autism/autism-screening">developmental autism screening</a> sets out what a full screening appointment involves.</p>

          <h2>The early signs the checklist actually asks about</h2>

          <p>The items cover social communication and play rather than physical milestones. We are not reprinting the questionnaire here. Its authors license the document and ask that people link to their own copy rather than republish it, so the official version sits at <a href="https://www.mchatscreen.com/" rel="nofollow noopener" target="_blank">mchatscreen.com</a>. What follows is what the questions are getting at, in plain terms.</p>

          <ul class="signs-list">
            <li><strong>Pointing to show, not only to get.</strong> Most toddlers point at things they want. The socially loaded version is pointing at something interesting purely so you will look at it too.</li>
            <li><strong>Following your point.</strong> You point across the room and say look. Does your child follow your finger to the thing, or look at your hand, or not respond at all?</li>
            <li><strong>Bringing things over to share.</strong> Carrying a toy across to you for no reason other than to show it, then looking at your face to see your reaction.</li>
            <li><strong>Responding to their own name.</strong> Not simply hearing it, but turning towards you when you say it while they are busy with something else.</li>
            <li><strong>Pretend play.</strong> Feeding a doll, talking into a toy phone, pouring from an empty cup. Using one thing to stand in for another is a developmental step, not just a game.</li>
            <li><strong>Checking your face for cues.</strong> Glancing at you in an unfamiliar situation to work out whether it is safe, and looking where you are looking.</li>
            <li><strong>Interest in other children.</strong> Watching them, moving towards them, trying to join in, rather than playing near them without noticing them.</li>
            <li><strong>Unusual repetitive finger or hand movements.</strong> Movements held close to the face or eyes, distinct from ordinary excited flapping.</li>
            <li><strong>Reactions to everyday sound.</strong> Distress at noises that other children in the same room do not react to at all.</li>
          </ul>

          <p>Read that list again and notice what is not on it. Speech is largely absent. A great many parents wait for words before raising a concern, and the screener does not, which is exactly why it can flag a child at 18 months. Our broader guide to the <a href="/autism/signs-of-autism">signs of autism across childhood</a> covers how this picture changes with age.</p>

          <h2>The questions where &lsquo;yes&rsquo; is the answer that counts</h2>

          <p>Most items are worded so that a no is the answer raising a flag. Does she point, does she respond to her name, does she pretend. A small number are inverted, so that a yes is what counts, and these tend to be the questions about unusual movements, sensitivity to sound, and whether you have ever wondered about your child&rsquo;s hearing.</p>

          <p>This is the most common reason a parent who scores the form at home arrives at a number that does not match their clinician&rsquo;s. It is worth knowing before you start. Read each question on its own terms rather than assuming every yes is reassuring.</p>

          <h2>What a score actually means</h2>

          <p>Scores run from 0 to 20 and fall into three bands. A total of 0 to 2 is low risk. A total of 3 to 7 is medium risk, and the parent then works through a set of follow-up questions with a clinician, who asks for concrete examples of each flagged behaviour. A total of 8 or above is high risk, and it is considered acceptable to skip the follow-up and refer straight for a <a href="/autism/autism-diagnostic-evaluation">diagnostic evaluation</a>.</p>

          <p>The follow-up interview is the part most often skipped, and it is doing much of the work. In the original validation study, published in <em>Pediatrics</em> in 2014 and covering 16,071 toddlers, the checklist plus follow-up gave a positive predictive value of 47.5% for autism. A 2023 meta-analysis in the same journal, pooling 15 studies and 49,841 children across ten countries, put it at 57.7%, and found it varied by group: 75.6% among children already considered more likely to be autistic, such as those with an autistic sibling, against 51.2% among children with no such history.</p>

          <p>So roughly half the children the checklist flags will not turn out to be autistic. Here is the part that usually gets left out. In that 2014 study, 94.6% of the children who screened positive had some developmental delay or concern that warranted intervention, and only 5.4% were judged to be developing typically. A positive M-CHAT is often not autism. It is almost never nothing.</p>

          <h2>Why a low score is not a clearance</h2>

          <p>A reassuring score is not the same as a clean bill of health. The authors of the 2023 meta-analysis were explicit that not all children with autism show features in early childhood, and that clinical judgement remains essential. That is precisely why the recommended schedule has two autism-specific screening points rather than one, plus surveillance at every visit.</p>

          <p>If your child scores low and you are still uneasy, that unease is information. The CDC treats parents as reliable sources of information about their own children. You do not need a failed screener to ask for a closer look.</p>

          <h2>Does the M-CHAT hold up for Indian families?</h2>

          <p>Here is something you will not find on most pages about this topic. For years the M-CHAT was used across India in translations that had never been culturally adapted or formally validated in Indian children.</p>

          <p>That changed recently. A 2024 study in <em>Indian Pediatrics</em> validated Hindi versions of three autism screening tools in children aged 16 to 30 months, comparing them against expert clinical assessment. The Hindi M-CHAT-R/F reported sensitivity of 95.2% and specificity of 94.4%, with excellent test-retest and inter-rater reliability.</p>

          <p>This matters practically. A screener asks about behaviour in the context of how a family plays and talks, so a version checked against Indian children in their own language stands on firmer ground than an informal translation. If a clinic hands you a Hindi form, it is reasonable to ask which one it is.</p>

          <div class="safety-card">
            <p><strong>Worth saying plainly:</strong> this article can help you decide whether to have your child screened. It is not a diagnosis, not a screening result, and not a substitute for assessment by a qualified clinician. A screener cannot rule autism in or out. If you have a concern about your child&rsquo;s development, raise it with a professional rather than waiting for the next scheduled visit.</p>
          </div>

          <h2>What to do next</h2>

          <p>The early signs of autism in toddlers described here are a reason to ask a question, not a verdict on your child. If yours is between 16 and 30 months and something has been nagging at you, the useful next step is a screening conversation with someone who can take a developmental history and, where the score points that way, work through the follow-up questions properly. Identifying it early is what opens access to support during the years when it does the most good.</p>

