  <h2>6. What helps at home, starting today</h2>

  <h3>Attention and follow-through</h3>
  <ul>
    <li><strong>One instruction at a time,</strong> with eye contact, and have it repeated back. Chains of instruction fail in working memory, not in willingness.</li>
    <li><strong>Externalise time.</strong> A visible timer beats "hurry up". Children with attention difficulties have a genuinely different sense of elapsed time.</li>
    <li><strong>Work in short blocks</strong> — 15 to 20 minutes with a real break — rather than one long homework session that ends in tears for everyone.</li>
    <li><strong>Reward starting, not finishing.</strong> The hard part is initiation.</li>
  </ul>

  <h3>Transitions and meltdowns</h3>
  <ul>
    <li><strong>Warn twice</strong> — five minutes, then one minute.</li>
    <li><strong>Use a visual schedule.</strong> Predictability lowers baseline anxiety more reliably than any reward chart.</li>
    <li><strong>Do not teach during a meltdown.</strong> Regulate first, discuss much later. Nothing is learned at peak distress.</li>
    <li><strong>Track antecedents.</strong> Note what happened in the 20 minutes before. Hunger, noise, and transitions explain most of it.</li>
  </ul>

  <h3>Sensory overload</h3>
  <ul>
    <li><strong>Heavy work</strong> before demanding activities — carrying, pushing, climbing.</li>
    <li><strong>A retreat space</strong> your child can use without asking permission and without it being a punishment.</li>
    <li><strong>Reduce the load in advance</strong> of predictable overload — birthday parties, malls, weddings — rather than managing the aftermath.</li>
  </ul>

