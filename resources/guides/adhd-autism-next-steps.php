  <h1>The Parent's ADHD &amp; Autism Assessment Guide</h1>
  <p class="lm-guide__lede">
    What the assessment actually involves, what each tool measures, what to ask before you pay anyone, and
    how to get your child's school to act on the result.
  </p>

  <div class="lm-guide__box">
    <p><strong>The one-line version.</strong> An assessment is worth doing when the answer would change what
    you do next — therapy, school accommodations, or an end to uncertainty that is shaping how you parent.
    If nothing would change, wait and re-check in three months.</p>
  </div>

  <h2>1. Before you book anything: rule out the imitators</h2>
  <p>Four things regularly produce ADHD- and autism-like behaviour and are far quicker to check. Doing these first has saved plenty of families an unnecessary assessment.</p>
  <table>
    <tr><th style="width:25%">Check</th><th>Why it matters</th></tr>
    <tr><td>Hearing</td><td>Glue ear and mild hearing loss produce speech delay, "not listening", and social withdrawal. Common, treatable, and routinely missed.</td></tr>
    <tr><td>Vision</td><td>Uncorrected vision looks like inattention, avoidance of written work, and clumsiness.</td></tr>
    <tr><td>Sleep</td><td>Chronically short or fragmented sleep in children presents as hyperactivity and irritability, not drowsiness. Two weeks of a fixed sleep window is a real diagnostic test.</td></tr>
    <tr><td>Anxiety</td><td>An anxious child avoids, freezes, refuses school, and struggles socially. From the outside this is easy to mistake for autism — and the treatment is different.</td></tr>
  </table>

  <h2>2. What the assessment involves</h2>
  <ol>
    <li><strong>Intake call (15 minutes, free at eMbrace).</strong> A clinician hears your concern and tells you whether an assessment is the right next step at all.</li>
    <li><strong>Developmental history (60–90 minutes).</strong> Pregnancy and birth, milestones, medical history, school reports, family history, and a detailed picture of the behaviours in context.</li>
    <li><strong>Direct assessment (2–4 sessions).</strong> Standardised tools with your child, chosen for their age and the question being asked.</li>
    <li><strong>School input.</strong> Teacher rating scales and, where useful, a classroom observation. Behaviour present in only one setting usually points somewhere other than ADHD or autism.</li>
    <li><strong>Feedback and report.</strong> A sit-down explanation in plain language and a written report with specific, actionable recommendations.</li>
  </ol>
  <p>End to end this typically runs two to three weeks at eMbrace, depending on how quickly the school responds.</p>

  <h2>3. What each tool actually measures</h2>
  <table>
    <tr><th style="width:22%">Tool</th><th>What it does</th></tr>
    <tr><td><strong>ADOS-2</strong></td><td>The current gold standard for autism. A structured, play- and conversation-based observation with your child, scored against defined criteria. Must be done in person by a trained administrator.</td></tr>
    <tr><td><strong>ADI-R / developmental interview</strong></td><td>A detailed structured interview with you about your child's history — the other half of an autism assessment.</td></tr>
    <tr><td><strong>Conners / Vanderbilt scales</strong></td><td>Parent and teacher ratings of attention, hyperactivity and impulsivity, compared to age norms. ADHD requires evidence across settings, which is why the teacher form is not optional.</td></tr>
    <tr><td><strong>WISC-V / WPPSI-IV</strong></td><td>Cognitive profile — verbal reasoning, visual-spatial, fluid reasoning, working memory, processing speed. Often the assessment that explains why a bright child is struggling in class.</td></tr>
    <tr><td><strong>Vineland-3</strong></td><td>Adaptive functioning — what your child actually does day to day, versus what they can do in a test room. Central to support planning and disability certification.</td></tr>
    <tr><td><strong>Achievement / LD batteries</strong></td><td>Reading, writing and maths against grade level. This is what identifies dyslexia, dysgraphia and dyscalculia — which frequently sit alongside ADHD.</td></tr>
    <tr><td><strong>Sensory profile</strong></td><td>How your child responds to sound, texture, movement and light. Drives occupational therapy planning.</td></tr>
  </table>

  <div class="lm-guide__box lm-guide__box--warn">
    <p><strong>A warning about cheap assessments.</strong> If a quote seems unusually low, ask which tools are
    included. An "assessment" that is a questionnaire plus a 30-minute chat is not an assessment, and the
    report it produces will not be accepted by a school board — you will end up paying twice.</p>
  </div>

  <h2>4. Questions to ask before you pay</h2>
  <ul>
    <li>Is the clinician RCI-certified? (In India this is what makes a report count.)</li>
    <li>Which specific tools will be used, and why those for my child's age and profile?</li>
    <li>How many sessions, over what period, and what is the all-inclusive cost with the report?</li>
    <li>Will the report be accepted by CBSE / ICSE / IB and by my child's school?</li>
    <li>Will you also see us for the therapy afterwards, or will I be starting a new search?</li>
    <li>What happens if you find nothing? (The honest answer — "that is a real result, and we will tell you" — is the one you want.)</li>
  </ul>

  <div class="lm-guide__page"></div>

  <h2>5. Getting the school to act</h2>
  <p>A diagnosis on its own changes nothing at school. What changes things is a written request naming specific, reasonable accommodations. Ask for few things, ask for concrete ones, and ask in writing.</p>

  <h3>Accommodations that schools in Delhi NCR commonly grant</h3>
  <table>
    <tr><th style="width:30%">Difficulty</th><th>Reasonable accommodation</th></tr>
    <tr><td>Attention / restlessness</td><td>Seat near the teacher, away from doors and windows; movement breaks; instructions repeated and written on the board; longer tasks broken into parts.</td></tr>
    <tr><td>Written output</td><td>Extra time; a scribe or laptop where indicated; reduced copying from the board; marks not deducted for handwriting.</td></tr>
    <tr><td>Reading / spelling</td><td>Reader for instructions; spelling exempted in content subjects; text-to-speech permitted.</td></tr>
    <tr><td>Sensory</td><td>Permission to leave a noisy assembly; ear defenders; a designated quiet space; advance notice of fire drills.</td></tr>
    <tr><td>Transitions / change</td><td>Advance warning of timetable changes; a visual schedule; a named adult to check in with.</td></tr>
    <tr><td>Exams</td><td>Extra time, separate room, and board-level concessions where the report supports them.</td></tr>
  </table>

