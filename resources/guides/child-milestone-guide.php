  <h1>The Delhi Parent's Milestone &amp; Early-Support Guide</h1>
  <p class="lm-guide__lede">
    Ages 0–12. What to expect, what to watch, what to do at home this week, and the point at which a
    professional opinion is genuinely worth paying for.
  </p>

  <div class="lm-guide__box">
    <p><strong>How to use this guide.</strong> Find your child's age band. Read the milestones as a pattern,
    not a checklist — children arrive at skills in different orders and at different speeds. What matters is
    whether several skills in one domain are consistently absent, whether the gap is widening rather than
    closing, and whether it is affecting daily life.</p>
  </div>

  <h2>1. Milestones by age</h2>

  <h3>0–12 months</h3>
  <table>
    <tr><th style="width:26%">Domain</th><th>Expect to see</th></tr>
    <tr><td>Communication</td><td>Quietens to your voice by 3 months; laughs and squeals by 6; babbles varied sounds ("ba-ba", "da-da") by 9; responds to their name by 9–12; one or two words with meaning by 12.</td></tr>
    <tr><td>Motor</td><td>Head steady by 4 months; rolls by 6; sits unsupported by 9; pulls to stand by 12; transfers objects hand to hand by 7–9.</td></tr>
    <tr><td>Social</td><td>Social smile by 2 months; recognises familiar faces by 4; enjoys peek-a-boo by 9; waves or claps by 12.</td></tr>
    <tr><td>Play &amp; learning</td><td>Follows a moving object with eyes; looks where you point (joint attention) by 12 months; explores objects by mouthing and banging.</td></tr>
  </table>

  <h3>1–2 years</h3>
  <table>
    <tr><th style="width:26%">Domain</th><th>Expect to see</th></tr>
    <tr><td>Communication</td><td>10–20 meaningful words by 18 months; points to request and to show; follows one-step instructions; 50+ words and two-word phrases approaching 24 months.</td></tr>
    <tr><td>Motor</td><td>Walks independently by 15 months; climbs; scribbles; stacks 2–4 blocks; drinks from an open cup with help.</td></tr>
    <tr><td>Social</td><td>Brings objects to show you; checks your face for reaction; shows affection to familiar people; brief separation distress is normal and expected.</td></tr>
    <tr><td>Play &amp; learning</td><td>Imitates household activity; simple pretend play emerging; matches or sorts by shape.</td></tr>
  </table>

  <h3>2–3 years</h3>
  <table>
    <tr><th style="width:26%">Domain</th><th>Expect to see</th></tr>
    <tr><td>Communication</td><td>Two- to three-word phrases; familiar adults understand about half of speech at 2, three-quarters at 3; follows two-step instructions; names common objects.</td></tr>
    <tr><td>Motor</td><td>Runs, kicks a ball, walks up stairs with a rail; turns single book pages; uses a spoon; starts undressing.</td></tr>
    <tr><td>Social</td><td>Notices and plays alongside other children; shows concern when someone is upset; begins to say "mine" (this is developmental, not rudeness).</td></tr>
    <tr><td>Behaviour</td><td>Tantrums are normal at this age. What we look at is frequency, how long they last, and whether your child can be comforted.</td></tr>
  </table>

  <h3>3–5 years</h3>
  <table>
    <tr><th style="width:26%">Domain</th><th>Expect to see</th></tr>
    <tr><td>Communication</td><td>Full sentences understandable to strangers; asks and answers what/where/why; tells a simple sequenced story; uses past tense.</td></tr>
    <tr><td>Motor</td><td>Hops, pedals, catches a large ball; draws a person with 2–4 parts by 4 and 6+ parts by 5; holds a pencil in a tripod grip.</td></tr>
    <tr><td>Social</td><td>Cooperative play with turn-taking; separates at school without prolonged distress; has a preferred playmate.</td></tr>
    <tr><td>Daily living</td><td>Daytime toilet independence by around 4; dresses with minor help; recovers from frustration within a few minutes.</td></tr>
  </table>

  <h3>6–8 years</h3>
  <table>
    <tr><th style="width:26%">Domain</th><th>Expect to see</th></tr>
    <tr><td>Learning</td><td>Reads class-level text with comprehension; writes legibly and finishes classwork; handles addition and subtraction at grade level.</td></tr>
    <tr><td>Attention</td><td>Sustains a task 15–20 minutes with occasional reminders; follows multi-step classroom instructions.</td></tr>
    <tr><td>Social</td><td>One or two steady friendships; names feelings; asks an adult for help when stuck.</td></tr>
    <tr><td>Wellbeing</td><td>Goes to school willingly; 9–11 hours of sleep; no frequent unexplained stomach aches or headaches.</td></tr>
  </table>

  <h3>9–12 years</h3>
  <table>
    <tr><th style="width:26%">Domain</th><th>Expect to see</th></tr>
    <tr><td>Learning</td><td>Keeps pace with class reading and writing demands; can summarise what they have read.</td></tr>
    <tr><td>Executive skills</td><td>Tracks homework and deadlines with occasional reminders; sustains focus around 30 minutes; packs their own bag.</td></tr>
    <tr><td>Social &amp; emotional</td><td>Maintains friendships and repairs minor conflict; names worries out loud; mood is broadly steady.</td></tr>
    <tr><td>Wellbeing</td><td>9–11 hours of sleep; accepts screen limits without extreme conflict; no persistent sadness or irritability beyond two weeks.</td></tr>
  </table>

