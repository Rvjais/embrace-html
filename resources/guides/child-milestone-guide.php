  <h2>4. If you decide to get an assessment</h2>
  <p>An assessment is worth doing when it will change what you do next. If the result would lead to therapy, school accommodations, or simply an end to the uncertainty that is affecting how you parent, it is worth it. If nothing would change, wait and re-check.</p>

  <h3>What a good assessment includes</h3>
  <ol>
    <li>A full developmental history with a parent, in person, taking 60–90 minutes — not a form.</li>
    <li>Standardised, age-appropriate tools administered directly with your child (for example ADOS-2 for autism, Conners for ADHD, WISC-V for cognitive profile, Vineland for adaptive functioning).</li>
    <li>Input from school, in writing.</li>
    <li>A feedback session where the findings are explained in plain language, with time for your questions.</li>
    <li>A written report that names the tools used, the scores, and specific recommendations — the format schools and examination boards require.</li>
  </ol>

  <h3>Questions to ask before you pay anyone</h3>
  <ul>
    <li>Which specific tools will you use, and why those?</li>
    <li>Is the clinician RCI-certified? (In India, this is the qualification that makes a report count.)</li>
    <li>How many sessions, over how long, and what is the total cost including the report?</li>
    <li>Will I get a written report, and will it be accepted by CBSE / IB / my child's school?</li>
    <li>What happens if the assessment finds nothing? (A good clinic will tell you that is a real and useful outcome.)</li>
  </ul>

