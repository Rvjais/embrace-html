  <h2>2. Signs that warrant a professional opinion promptly</h2>
  <p>These are not proof of anything. They are the patterns that, in our clinic, most often turn out to matter — and the ones where waiting costs the most.</p>

  <div class="lm-guide__box lm-guide__box--warn">
    <p><strong>At any age</strong> — loss of a skill your child already had (words, gestures, toilet training). Regression always warrants a same-month appointment, not a wait-and-see.</p>
  </div>

  <ul>
    <li><strong>By 12 months</strong> — no babbling, no pointing, no waving, no response to their name.</li>
    <li><strong>By 18 months</strong> — fewer than six words, no pointing to show you things, no interest in other people.</li>
    <li><strong>By 24 months</strong> — no two-word phrases, unfamiliar adults understand almost nothing, no pretend play.</li>
    <li><strong>By 3 years</strong> — speech unclear to strangers, cannot follow two-step instructions, no interest in other children, extreme distress at routine change.</li>
    <li><strong>By 5 years</strong> — cannot tell a simple story, no cooperative play, still not toilet-trained in the day, meltdowns lasting 20+ minutes several times a week.</li>
    <li><strong>School age</strong> — reading or writing well behind classmates, daily school refusal, no friendships at all, teacher raising concerns you do not see at home (or the reverse).</li>
    <li><strong>Any age</strong> — hurting themselves, talking about not wanting to be alive, or a change in personality that has lasted more than a few weeks. Call us or Tele-MANAS (14416) the same day.</li>
  </ul>

  <h2>3. What to do at home this week</h2>

  <h3>If communication scored low</h3>
  <ul>
    <li><strong>Narrate, do not quiz.</strong> "We're washing the red cup" beats "What colour is this?" Children learn language from commentary far faster than from testing.</li>
    <li><strong>Wait five seconds.</strong> Ask, then count to five in your head. Most adults fill the gap before a child with a slower processing speed has finished assembling their answer.</li>
    <li><strong>Add one word.</strong> They say "juice", you say "more juice". Model one step above where they are, not five.</li>
    <li><strong>Get hearing checked</strong> if this domain scored low. Undetected glue ear and hearing loss are the most common reversible cause of speech delay, and they are cheap to test.</li>
  </ul>

  <h3>If social and emotional scored low</h3>
  <ul>
    <li><strong>Ten minutes of floor time daily.</strong> No phone, no teaching, no correcting — you follow their lead entirely. This is the single highest-yield intervention parents can run at home.</li>
    <li><strong>Name the feeling before you fix it.</strong> "You're furious the tower fell." Regulation is learned from being understood, then calmed — in that order.</li>
    <li><strong>Small, structured playdates.</strong> One child, one hour, one clear activity. Group settings overload a child who is still learning the mechanics of interaction.</li>
  </ul>

  <h3>If motor scored low</h3>
  <ul>
    <li><strong>Heavy work daily</strong> — carrying, pushing, climbing, hanging. It organises the sensory system and calms most children noticeably.</li>
    <li><strong>Vertical surfaces for fine motor.</strong> Drawing on paper taped to a wall builds wrist stability that pencil grip depends on.</li>
    <li><strong>Everyday practice</strong> — buttons, zips, pouring, tearing paper. Ten purposeful minutes beats an hour of worksheets.</li>
  </ul>

  <h3>If attention or behaviour scored low</h3>
  <ul>
    <li><strong>Fix sleep first.</strong> One hour of lost sleep looks exactly like inattention in a child. Consistent bedtime, no screens in the last hour, dark and cool room, for two full weeks.</li>
    <li><strong>Shorten the instruction.</strong> One step, eye contact, and have them repeat it back. Long chains of instruction fail in working memory, not in willingness.</li>
    <li><strong>Warn before transitions.</strong> A five-minute and one-minute warning removes a large share of meltdowns without any negotiation.</li>
    <li><strong>Catch the behaviour you want.</strong> Five specific positives for every correction, for two weeks. Then judge whether the behaviour is the problem.</li>
  </ul>

