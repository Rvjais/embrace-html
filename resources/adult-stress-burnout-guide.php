        <p style="margin:.8rem 0 0;color:#55596b;line-height:1.7">Stress and burnout are mostly tied to one area, usually work, while anxiety and depression tend to show up across many areas of life. Anxiety brings persistent worry and a restless, on-edge energy; depression brings a heavy, flat mood and loss of interest not tied to one situation. They overlap, and burnout can lead into either, which is why the guide covers all four side by side rather than just one.</p>
