<p>If you are searching for a child psychiatrist in Delhi NCR, the honest answer first: we are a psychology and therapy practice, not a psychiatric clinic. For psychiatric assessment, consultation and medication management, we work with Sukoon across Delhi NCR, so you are not left to find a psychiatrist yourself. This page explains how that coordination works and what each side of the care actually covers.</p>
<h2>What a child and adolescent psychiatrist does</h2>
<p>A child and adolescent psychiatrist is a medical doctor who assesses for a formal diagnosis where medication may help, and who can prescribe and review it. That sits alongside, not instead of, the psychological and therapy work.</p>
<ul>
<li>Psychiatric assessment and diagnosis for conditions such as ADHD, anxiety, depression and OCD</li>
<li>A decision on whether medication is appropriate, and which, discussed honestly with you</li>
<li>Ongoing review and adjustment once medication has started</li>
<li>Coordination with your child's therapist and school, with your consent</li>
</ul>
<h2>How this fits with assessment and therapy at eMbrace</h2>
<p>Families most often come to this question through an existing concern — an ADHD or autism assessment, a diagnosis of anxiety or depression in a child or teen, or a case where therapy and school support have not been enough on their own. Our clinical and child psychologists carry out the psychological assessment and deliver the therapy. Where the picture suggests a medical and medication opinion is also worth having, we coordinate that referral to Sukoon directly, so you are not sent away to start again with someone who knows nothing about your child.</p>
<p>With your consent, we share the assessment and therapy notes that are relevant, so the psychiatric opinion is informed by the same picture your therapist is working from, rather than a fresh ten-minute history.</p>
<h2>When psychiatric input is usually considered</h2>
<p>Medication is one option among several, and it is never assumed to be the first one. A psychiatric opinion is usually worth having when:</p>
<ul>
<li>ADHD symptoms are significantly affecting school, friendships or home life despite therapy and school accommodations</li>
<li>Anxiety, depression or OCD symptoms are severe enough to interfere with daily functioning</li>
<li>A clear diagnosis already exists and the family wants to understand medication as an option, not necessarily to start it</li>
<li>Progress in therapy has stalled and a treating clinician recommends a medical review alongside it</li>
</ul>
<h2>What happens, step by step</h2>
<p>You start with a free 15-minute intake call with our team, the same as for any other concern. If a psychiatric opinion looks relevant, we explain why, answer your questions, and coordinate the referral to Sukoon directly rather than leaving you to search for a provider. Your child's therapy continues in parallel, and with your consent the two sides of the care stay in touch.</p>
