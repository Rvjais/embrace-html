// The shared hub-page template: the lede paragraph directly under the article <h2>.
const INTRO = /(<p class="text-lg text-gray-700 leading-relaxed font-light mb-8">[\s\S]*?<\/p>)/;
const esc = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const MARKER_RE = new RegExp(esc(START) + '[\\s\\S]*?' + esc(END));

let inserted = 0, updated = 0;
const failed = [];

for (const [rel, sentence] of Object.entries(COPY)) {
  const full = path.join(ROOT, rel);
  if (!fs.existsSync(full)) { failed.push(`${rel} (file missing)`); continue; }

  let text = fs.readFileSync(full, 'utf8');
  const para = `${START}\n            <p class="text-base text-gray-700 leading-relaxed mb-8">${sentence}</p>\n            ${END}`;

  if (MARKER_RE.test(text)) {
    text = text.replace(MARKER_RE, para);
    updated++;
  } else if (INTRO.test(text)) {
    text = text.replace(INTRO, `$1\n            ${para}`);
    inserted++;
  } else {
    failed.push(`${rel} (intro paragraph not found)`);
    continue;
  }
  fs.writeFileSync(full, text);
}

console.log(`In-content location links — inserted: ${inserted}, updated: ${updated}, pages: ${Object.keys(COPY).length}`);
if (failed.length) console.log(`  FAILED: ${failed.join(', ')}`);
