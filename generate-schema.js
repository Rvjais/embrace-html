/**
 * Generates a single JSON-LD @graph per page and writes it between the SCHEMA
 * markers, just before </head>.
 *
 *     node generate-schema.js
 *
 * Design notes
 * ------------
 * - One consolidated @graph per page instead of several loose <script> blocks, so
 *   the Organization is defined once with a stable @id and every other node
 *   references it rather than redeclaring it.
 * - Questions, answers and breadcrumb trails are READ OUT OF THE PAGE MARKUP, never
 *   invented. Google requires FAQ answers to be visible on the page, and these are —
 *   they come from the page's own accordion.
 * - The legacy hand-written blocks (45 MedicalWebPage + 26 MedicalBusiness) are
 *   replaced. Their hand-authored MedicalCondition detail was lifted into
 *   schema-medical-entities.json and is re-applied here, so nothing editorial was
 *   lost. Those blocks also carried the same root-level URL bug as the canonicals
 *   ("/ados-2-assessment" for a page that actually lives at
 *   /autism/ados-2-assessment); the generated graph uses the real clean URL.
 * - Location pages get a Service node with `areaServed`, NOT a LocalBusiness with a
 *   fabricated street address. eMbrace has three real clinics; the other seven areas
 *   are served, not sited. Inventing addresses there would be fake NAP data.
 */
