function buildGraph(rel, html) {
  const url = urlFor(rel);
  const pageId = `${url}#webpage`;
  const title = getTitle(html) || 'eMbrace';
  const desc = getDesc(html);
  const graph = [];

  // Top-level so every {"@id": ".../#logo"} reference resolves within the graph.
  graph.push({
    '@type': 'ImageObject', '@id': `${BASE}/#logo`,
    url: LOGO, contentUrl: LOGO, caption: 'eMbrace',
  });
  graph.push(organizationNode());
  graph.push({
    '@type': 'WebSite', '@id': SITE_ID, url: `${BASE}/`, name: 'eMbrace',
    publisher: { '@id': ORG_ID }, inLanguage: 'en-IN',
  });

  const type = pageTypeFor(rel);
  const page = {
    '@type': type,
    '@id': pageId,
    url,
    name: title,
    isPartOf: { '@id': SITE_ID },
    about: { '@id': ORG_ID },
    inLanguage: 'en-IN',
  };
  if (desc) page.description = desc;
  if (type === 'MedicalWebPage' && MEDICAL_ENTITIES[rel]) {
    page.mainEntity = MEDICAL_ENTITIES[rel].mainEntity;
    if (MEDICAL_ENTITIES[rel].aspect) page.aspect = MEDICAL_ENTITIES[rel].aspect;
  }

  const crumbs = extractBreadcrumb(html);
  if (crumbs) {
    page.breadcrumb = { '@id': `${url}#breadcrumb` };
    graph.push({
      '@type': 'BreadcrumbList',
      '@id': `${url}#breadcrumb`,
      itemListElement: crumbs.map((c, i) => {
        const item = { '@type': 'ListItem', position: i + 1, name: c.name };
        if (c.url) item.item = c.url; // last crumb is the current page: no item, per Google
        return item;
      }),
    });
  }
  graph.push(page);

  const faqs = extractFaqs(html);
  if (faqs.length) {
    graph.push({
      '@type': 'FAQPage',
      '@id': `${url}#faq`,
      url,
      name: `${title} — Frequently Asked Questions`,
      isPartOf: { '@id': pageId },
      inLanguage: 'en-IN',
      mainEntity: faqs.map(f => ({
        '@type': 'Question',
        name: f.q,
        acceptedAnswer: { '@type': 'Answer', text: f.a },
      })),
    });
  }

  const loc = parseLocation(rel);
  if (loc) {
    graph.push({
      '@type': 'Service',
      '@id': `${url}#service`,
      name: `${loc.service} in ${loc.area}`,
      serviceType: loc.service,
      provider: { '@id': ORG_ID },
      areaServed: { '@type': 'Place', name: areaServedName(loc.area) },
      availableChannel: {
        '@type': 'ServiceChannel',
        serviceUrl: url,
        servicePhone: PHONE,
      },
      audience: { '@type': 'PeopleAudience', audienceType: 'Children, adolescents and adults' },
    });
  }

  if (isBlogPost(rel)) {
    const posting = {
      '@type': 'BlogPosting',
      '@id': `${url}#article`,
      isPartOf: { '@id': pageId },
      mainEntityOfPage: { '@id': pageId },
      headline: getH1(html) || title,
      url,
      inLanguage: 'en-IN',
      // The practice is the author of record; a named clinician signs off on the
      // clinical content and appears as reviewedBy below when the page says so.
      author: { '@id': ORG_ID },
      publisher: { '@id': ORG_ID },
      image: `${BASE}/og-image.png`,
    };
    if (desc) posting.description = desc;

    const published = getPublished(html);
    if (published) {
      posting.datePublished = published;
      posting.dateModified = published;
    }

    const reviewer = getReviewer(html);
    if (reviewer) {
      posting.reviewedBy = { '@type': 'Person', name: reviewer, worksFor: { '@id': ORG_ID } };
    }

    page.mainEntity = { '@id': `${url}#article` };
    graph.push(posting);
  }

  if (rel === 'contact-us.php') {
    page.mainEntity = { '@id': ORG_ID };
  }

  return { '@context': 'https://schema.org', '@graph': graph };
}

/* ------------------------------------------------------------------ writing */

const esc = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
// Consume the block's own indentation and trailing newline too, otherwise each run
// leaves an orphaned blank line behind and every file grows by a line per run.
const MARKER_RE = new RegExp('[ \\t]*' + esc(START) + '[\\s\\S]*?' + esc(END) + '[ \\t]*\\r?\\n?');
// Legacy hand-written blocks, replaced by the generated graph.
const LEGACY_RE = /[ \t]*<script[^>]*type="application\/ld\+json"[^>]*>[\s\S]*?<\/script>\s*/gi;

const stats = { written: 0, faqPages: 0, faqQuestions: 0, crumbs: 0, services: 0, posts: 0, legacyRemoved: 0, preserved: 0, noHead: [] };

for (const rel of walk(ROOT).sort()) {
  const full = path.join(ROOT, rel);
  let html = fs.readFileSync(full, 'utf8');

  // Drop any previously generated block first so the legacy sweep cannot eat it.
  html = html.replace(MARKER_RE, '');

  const before = html;
  html = html.replace(LEGACY_RE, '');
  if (html !== before) stats.legacyRemoved++;

  const graph = buildGraph(rel, html);
  if (MEDICAL_ENTITIES[rel]) stats.preserved++;
  const json = JSON.stringify(graph, null, 2);
  const block = `${START}\n<script type="application/ld+json">\n${json}\n</script>\n${END}\n`;

  if (!/<\/head>/i.test(html)) { stats.noHead.push(rel); continue; }
  // Collapse any blank lines left by earlier runs so spacing stays stable.
  html = html.replace(/(?:[ \t]*\r?\n){2,}([ \t]*<\/head>)/i, '\n$1');
  html = html.replace(/([ \t]*)<\/head>/i, (m, indent) =>
    block.split('\n').map(l => (l ? indent + l : l)).join('\n') + `${indent}</head>`);

  fs.writeFileSync(full, html);
  stats.written++;

  const faq = graph['@graph'].find(n => Array.isArray(n.mainEntity) && n['@type'] === 'FAQPage');
  if (faq) { stats.faqPages++; stats.faqQuestions += faq.mainEntity.length; }
  if (graph['@graph'].some(n => n['@type'] === 'BreadcrumbList')) stats.crumbs++;
  if (graph['@graph'].some(n => n['@type'] === 'Service')) stats.services++;
  if (graph['@graph'].some(n => n['@type'] === 'BlogPosting')) stats.posts++;
}

console.log(`Schema written to ${stats.written} pages (legacy blocks replaced on ${stats.legacyRemoved}).`);
console.log(`  FAQPage nodes: ${stats.faqPages} (${stats.faqQuestions} questions)`);
console.log(`  BreadcrumbList nodes: ${stats.crumbs}`);
console.log(`  Service nodes (location pages): ${stats.services}`);
console.log(`  BlogPosting nodes: ${stats.posts}`);
console.log(`  MedicalCondition detail applied: ${stats.preserved}`);
if (stats.noHead.length) console.log(`  NO </head> — skipped: ${stats.noHead.join(', ')}`);
