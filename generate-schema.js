/* ------------------------------------------------------------- page walking */

const SKIP_DIRS = new Set(['node_modules', 'dist', '.git', 'api', 'components', '_external', 'assets', 'assets_backup', 'practitioner-images', 'practitioner-images_backup', 'embrace-media', 'videos', '__pycache__']);
// blog.php is a bare 301 stub pointing at /blog/; it has no markup to describe.
const SKIP_FILES = new Set(['build.php', 'blog.php']);

function walk(dir, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (e.name.startsWith('.')) continue;
    const f = path.join(dir, e.name);
    if (e.isDirectory()) { if (SKIP_DIRS.has(e.name)) continue; walk(f, out); }
    else if (e.name.endsWith('.php')) {
      const rel = path.relative(ROOT, f).split(path.sep).join('/');
      if (!SKIP_FILES.has(rel)) out.push(rel);
    }
  }
  return out;
}

// A page at `<dir>/index.php` is served at `/<dir>/`, slash included: nginx
// 301s `/<dir>` to `/<dir>/` as soon as the directory exists, so the slashless
// form is only ever a redirect.
const urlFor = rel =>
  rel === 'index.php' ? `${BASE}/`
  : rel.endsWith('/index.php') ? `${BASE}/` + rel.replace(/index\.php$/, '')
  : `${BASE}/` + rel.replace(/\.php$/, '');

/** Turn an internal href from the markup into the site's clean URL form. */
function cleanHref(href) {
  if (!href) return null;
  if (/^https?:/i.test(href)) return href;
  let u = href.split('#')[0].split('?')[0];
  if (u === '/index.php' || u === '/' || u === '/index') return `${BASE}/`;
  u = u.replace(/\.php$/, '');
  return u.startsWith('/') ? BASE + u : `${BASE}/${u}`;
}

/* --------------------------------------------------------- text extraction */

const decode = s => s
  .replace(/<[^>]*>/g, ' ')
  .replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>')
  .replace(/&quot;/g, '"').replace(/&#39;|&apos;/g, "'").replace(/&nbsp;/g, ' ')
  .replace(/&rsquo;/g, '’').replace(/&lsquo;/g, '‘')
  .replace(/&ldquo;/g, '“').replace(/&rdquo;/g, '”')
  .replace(/&ndash;/g, '–').replace(/&mdash;/g, '—').replace(/&hellip;/g, '…')
  .replace(/\s+/g, ' ').trim();

const attr = (html, re) => { const m = html.match(re); return m ? decode(m[1]) : null; };

const getTitle = h => attr(h, /<title>([\s\S]*?)<\/title>/i);
const getDesc = h =>
  attr(h, /<meta[^>]*name="description"[^>]*content="([^"]*)"/i) ||
  attr(h, /<meta[^>]*content="([^"]*)"[^>]*name="description"/i);

/** The visible <h1>, which is the real headline; <title> carries SEO padding. */
const getH1 = h => attr(h, /<h1[^>]*>([\s\S]*?)<\/h1>/i);

/** ISO publication date from the article:published_time meta tag. */
const getPublished = h =>
  attr(h, /<meta[^>]*property="article:published_time"[^>]*content="([^"]*)"/i) ||
  attr(h, /<meta[^>]*content="([^"]*)"[^>]*property="article:published_time"/i);

/**
 * Reviewer name from the visible author card, e.g. "Reviewed by Dr. Supriya
 * Malik". Read out of the page like everything else here, never invented: if a
 * post carries no author card, the BlogPosting simply gets no reviewer.
 */
function getReviewer(html) {
  const m = html.match(/<div class="author-card"[\s\S]*?<strong>([\s\S]*?)<\/strong>/i);
  if (!m) return null;
  const name = decode(m[1]).replace(/^Reviewed by\s+/i, '').trim();
  return name || null;
}

/** Pull visible Q&A pairs out of whichever accordion pattern the page uses. */
function extractFaqs(html) {
  const out = [];
  const push = (q, a) => {
    q = decode(q); a = decode(a);
    if (q && a && q.length >= 8 && q.length <= 300 && a.length >= 25) {
      a = a.slice(0, 1200);
      if (!out.some(x => x.q === q)) out.push({ q, a });
    }
  };

  // Pattern A — topic and location pages: <div class="faq-item"> button>span + p
  for (const c of html.split(/<div class="faq-item"/).slice(1)) {
    const q = c.match(/<span[^>]*>([\s\S]*?)<\/span>/);
    const a = c.match(/<p[^>]*>([\s\S]*?)<\/p>/);
    if (q && a) push(q[1], a[1]);
  }
  if (out.length) return out;

  // Pattern B — homepage accordion
  for (const m of html.matchAll(/<span class="font-semibold text-sm md:text-base 2xl:text-lg text-gray-900 pr-4">([\s\S]*?)<\/span>[\s\S]*?<p class="px-5[^"]*">([\s\S]*?)<\/p>/g)) {
    push(m[1], m[2]);
  }
  if (out.length) return out;

  // Pattern C — the dedicated /faq page
  for (const c of html.split('<div class="bg-white rounded-lg shadow-sm overflow-hidden">').slice(1)) {
    const q = c.match(/<span class="font-medium text-gray-800[^"]*"[^>]*>([\s\S]*?)<\/span>/);
    if (!q) continue;
    const rest = c.slice(c.indexOf('</button>') + 9);
    push(q[1], rest);
  }
  return out;
}

/** Read the visible breadcrumb trail. */
function extractBreadcrumb(html) {
  const m = html.match(/<div class="[^"]*breadcrumbs"[\s\S]*?<div[^>]*>([\s\S]*?)<\/div>/);
  if (!m) return null;
  const items = [];
  for (const a of m[1].matchAll(/<a[^>]*href="([^"]*)"[^>]*>([\s\S]*?)<\/a>/g)) {
    const name = decode(a[2]);
    if (name) items.push({ name, url: cleanHref(a[1]) });
  }
  const last = m[1].match(/<span class="text-gray-800 font-medium">([\s\S]*?)<\/span>/);
  if (last) { const n = decode(last[1]); if (n) items.push({ name: n, url: null }); }
  return items.length > 1 ? items : null;
}

